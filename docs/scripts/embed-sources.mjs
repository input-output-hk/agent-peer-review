#!/usr/bin/env node
// Generates docs/schemas.mdx and docs/skills.mdx from the package's own source of
// truth (schemas/*.json, examples/*.json, skills/*.md) so the published docs can
// never drift from the code. Run via `npm run embed`; `build` and `start` run it
// automatically. No dependencies beyond Node's standard library.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const docsDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.join(docsDir, "..");
const schemasDir = path.join(repoRoot, "schemas");
const examplesDir = path.join(repoRoot, "examples");
const skillsDir = path.join(repoRoot, "skills");

const HEADER = "{/* AUTO-GENERATED by scripts/embed-sources.mjs — do not edit */}";

const readTrimmed = (filePath) => readFileSync(filePath, "utf8").trim();

/** Collapse accidental blank-line runs left by the join() below and ensure a trailing newline. */
const finalize = (lines) => lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";

// ---------------------------------------------------------------------------
// schemas.mdx: one section per schema in core/model.ts, JSON Schema + example.
// ---------------------------------------------------------------------------

const SCHEMAS = [
  {
    heading: "Config",
    file: "config.schema.json",
    example: "config.json",
    purpose:
      "Machine-local settings resolved before every command: your GitHub login, default repository, " +
      "custom skills directory, and whether checks may run build or test scripts.",
  },
  {
    heading: "Review Request",
    file: "review-request.schema.json",
    example: "review-request.json",
    purpose:
      "The input to `review.create`: the pull request to review, the skills to attach, and the " +
      "reviewers to request.",
  },
  {
    heading: "Claim Marker",
    file: "claim-marker.schema.json",
    example: null,
    purpose:
      "The JSON payload embedded in the claim comment. It pins a review to a commit SHA and records " +
      "who claimed it and from which machine.",
  },
  {
    heading: "Review Result",
    file: "review-result.schema.json",
    example: "review-result.json",
    purpose: "The input to `review.complete`: the review event, the summary, and any inline comments.",
  },
  {
    heading: "Enrichment",
    file: "enrichment.schema.json",
    example: null,
    purpose:
      "The input to `review.enrich`: an enricher's overall verdict, summary, and any new findings the " +
      "primary review missed.",
  },
  {
    heading: "Label Spec",
    file: "label-spec.schema.json",
    example: null,
    purpose:
      "One label definition, a name, a color, and a description, applied when `labels.bootstrap` " +
      "provisions a repository.",
  },
];

function buildSchemasPage() {
  const lines = [
    "---",
    "id: schemas",
    "title: Schemas",
    "---",
    "",
    HEADER,
    "",
    "Every payload the CLI and the MCP server accept or return is validated against a schema. The six " +
      "schemas below are generated from the single zod source of truth in `core/model.ts` by " +
      "`scripts/gen-schemas.ts`, and continuous integration fails the build if the checked-in files " +
      "under `schemas/` ever drift from that source. What you read here is exactly what the package " +
      "enforces at runtime.",
    "",
  ];

  for (const schema of SCHEMAS) {
    lines.push(`## ${schema.heading}`, "", schema.purpose, "", "```json", readTrimmed(path.join(schemasDir, schema.file)), "```", "");
    if (schema.example) {
      lines.push("**Example:**", "", "```json", readTrimmed(path.join(examplesDir, schema.example)), "```", "");
    }
  }

  return finalize(lines);
}

// ---------------------------------------------------------------------------
// skills.mdx: review + orchestration first, then every specialty in
// SKILL_NAMES order. The specialty names are parsed out of core/labels.ts
// itself, rather than duplicated here, so adding a specialty never requires
// touching this script: contributing a skill is only the 3 steps documented
// on the "Contributing a skill" page. Full file content is embedded verbatim,
// so nested ``` fences inside a skill file cannot break the outer fence.
// ---------------------------------------------------------------------------

function readSkillNames() {
  const src = readFileSync(path.join(repoRoot, "core", "labels.ts"), "utf8");
  const arrayLiteral = /export const SKILL_NAMES = \[([^\]]*)\]/.exec(src);
  if (!arrayLiteral) throw new Error("embed-sources: could not find SKILL_NAMES in core/labels.ts");
  const names = [...arrayLiteral[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  if (names.length === 0) throw new Error("embed-sources: SKILL_NAMES parsed to an empty list");
  return names;
}

const SKILL_ORDER = ["review", "orchestration", ...readSkillNames()];

function frontmatterDescription(raw) {
  if (!raw.startsWith("---")) return null;
  const end = raw.indexOf("\n---", 3);
  if (end === -1) return null;
  const match = /^description:\s*(.+)$/m.exec(raw.slice(0, end));
  return match ? match[1].trim() : null;
}

function buildSkillsPage() {
  const lines = [
    "---",
    "id: skills",
    "title: Skills",
    "---",
    "",
    HEADER,
    "",
    "A review runs the default checklist in `review` when a pull request carries no skill label. Adding " +
      "one or more bare skill labels layers specialty guidance on top of that default. The `claim` " +
      "operation composes the matched skill files on the server side and hands the full text to the " +
      "calling agent, so a Claude host, a Codex host, and a pi.dev host all receive identical " +
      "instructions. Any label that is not a recognized skill name is ignored.",
    "",
  ];

  for (const name of SKILL_ORDER) {
    const raw = readFileSync(path.join(skillsDir, `${name}.md`), "utf8");
    const description = frontmatterDescription(raw);
    lines.push(`## ${name}`, "");
    if (description) lines.push(`*${description}*`, "");
    lines.push("~~~~markdown", raw.trimEnd(), "~~~~", "");
  }

  return finalize(lines);
}

writeFileSync(path.join(docsDir, "schemas.mdx"), buildSchemasPage());
writeFileSync(path.join(docsDir, "skills.mdx"), buildSkillsPage());
console.log("embed-sources: wrote docs/schemas.mdx and docs/skills.mdx");
